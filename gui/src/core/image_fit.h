// ============================================================================
//  gui/src/core/image_fit.h — 壁纸"等比填满"的裁剪几何（纯函数，可单测）
//
//  壁纸要铺满整个窗口且**不能变形**，所以不是拉伸，而是"等比缩放 + 居中裁切"：
//  先用 centeredCropRect() 算出源图上要保留的那块，再把它缩放到目标矩形。
// ============================================================================
#pragma once

#include <QRect>
#include <QSize>

namespace core {

/// 居中裁切：返回源图里"宽高比与 target 一致、面积最大"的那块矩形。
///
/// 例：256×256 的源填 1280×800 的目标 → 返回 (0,48,256,160)（上下各切 48）
///     1280×800 的源填 400×400 的目标 → 返回 (240,0,800,800)（左右各切 240）
/// 退化输入（任一维 <= 0）→ 返回空矩形（调用方据此跳过绘制）。
QRect centeredCropRect(const QSize& source, const QSize& target);

} // namespace core
